-- Raw provider payload storage and API-call audit log.
-- The default partition prevents ingestion from failing before monthly partitions
-- have been provisioned. Create explicit monthly partitions as part of maintenance.
CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS raw.api_responses (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    provider            text NOT NULL,
    endpoint            text NOT NULL,
    request_params      jsonb NOT NULL DEFAULT '{}'::jsonb,
    response_status     integer,
    payload             jsonb NOT NULL,
    payload_hash        char(64) NOT NULL,
    ingested_at         timestamptz NOT NULL DEFAULT now(),
    ingested_date       date NOT NULL DEFAULT CURRENT_DATE,
    dag_run_id          text,
    CONSTRAINT api_responses_status_range
        CHECK (response_status IS NULL OR response_status BETWEEN 100 AND 599),
    CONSTRAINT api_responses_hash_format
        CHECK (payload_hash ~ '^[0-9a-f]{64}$'),
    PRIMARY KEY (id, ingested_date)
) PARTITION BY RANGE (ingested_date);

CREATE TABLE IF NOT EXISTS raw.api_responses_default
    PARTITION OF raw.api_responses DEFAULT;

CREATE INDEX IF NOT EXISTS api_responses_provider_ingested_idx
    ON raw.api_responses (provider, ingested_at DESC);
CREATE INDEX IF NOT EXISTS api_responses_payload_hash_idx
    ON raw.api_responses (payload_hash);

CREATE TABLE IF NOT EXISTS public.ingestion_request_log (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id          uuid NOT NULL,
    dag_run_id          text,
    provider            text NOT NULL,
    endpoint            text NOT NULL,
    request_params      jsonb NOT NULL DEFAULT '{}'::jsonb,
    started_at          timestamptz NOT NULL DEFAULT now(),
    completed_at        timestamptz,
    latency_ms          integer,
    http_status         integer,
    record_count        integer NOT NULL DEFAULT 0,
    outcome             text NOT NULL DEFAULT 'started',
    error_message       text,
    CONSTRAINT ingestion_request_log_latency_nonnegative
        CHECK (latency_ms IS NULL OR latency_ms >= 0),
    CONSTRAINT ingestion_request_log_record_count_nonnegative
        CHECK (record_count >= 0),
    CONSTRAINT ingestion_request_log_status_range
        CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
    CONSTRAINT ingestion_request_log_outcome_valid
        CHECK (outcome IN ('started', 'succeeded', 'http_error', 'network_error', 'rate_limited'))
);

CREATE INDEX IF NOT EXISTS ingestion_request_log_started_at_idx
    ON public.ingestion_request_log (started_at DESC);
CREATE INDEX IF NOT EXISTS ingestion_request_log_provider_outcome_idx
    ON public.ingestion_request_log (provider, outcome, started_at DESC);
